#!/usr/bin/env node
/**
 * Generates the placeholder assets the content collections point at:
 *
 *   public/research/placeholder-NN.pdf   small but valid single-font PDFs (varying sizes,
 *                                         so file-size labels in the research library mean something)
 *   src/assets/blog/cover-NN.svg          solid-colour 1200x800 SVGs with a text label
 *
 * The gallery uses real photos (see scripts/prepare-photos.mjs), so no gallery placeholders
 * are generated any more. Nothing is downloaded. Run with: node scripts/make-placeholder-assets.mjs
 * Existing files are overwritten. Delete this script once the owner supplies real assets.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

/* ------------------------------------------------------------------ PDFs */

const PDF_COUNT = 9;
const LINES_PER_PAGE = 40;

/** Escapes a string for use inside a PDF literal string `( ... )`. */
function pdfString(text) {
  return text.replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');
}

/**
 * Builds a minimal, valid PDF 1.4 file with one Helvetica font and as many A4 pages as the
 * lines need. Text must be representable in WinAnsi (Latin-1 superset): the Romanian letters
 * ă, ș and ț are not, so the placeholder copy avoids them on purpose.
 */
function buildPdf(lines) {
  const pages = [];
  for (let i = 0; i < lines.length; i += LINES_PER_PAGE) {
    pages.push(lines.slice(i, i + LINES_PER_PAGE));
  }

  // Object numbering: 1 catalog, 2 pages, 3 font, then (page, contents) pairs.
  const objects = [];
  const pageObjectNumbers = [];
  const firstPageObject = 4;
  pages.forEach((_, index) => pageObjectNumbers.push(firstPageObject + index * 2));

  objects.push('<< /Type /Catalog /Pages 2 0 R >>');
  objects.push(
    `<< /Type /Pages /Kids [${pageObjectNumbers.map((n) => `${n} 0 R`).join(' ')}] /Count ${pages.length} >>`,
  );
  objects.push('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>');

  pages.forEach((pageLines, index) => {
    const pageNumber = firstPageObject + index * 2;
    const contentNumber = pageNumber + 1;
    const content = [
      'BT',
      '/F1 11 Tf',
      '14 TL',
      '56 780 Td',
      ...pageLines.map((line) => `(${pdfString(line)}) Tj T*`),
      'ET',
    ].join('\n');
    objects.push(
      `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 3 0 R >> >> /Contents ${contentNumber} 0 R >>`,
    );
    objects.push(
      `<< /Length ${Buffer.byteLength(content, 'latin1')} >>\nstream\n${content}\nendstream`,
    );
  });

  let out = '%PDF-1.4\n%\xE2\xE3\xCF\xD3\n';
  const offsets = [];
  objects.forEach((body, index) => {
    offsets.push(Buffer.byteLength(out, 'latin1'));
    out += `${index + 1} 0 obj\n${body}\nendobj\n`;
  });
  const xrefOffset = Buffer.byteLength(out, 'latin1');
  out += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  out += offsets.map((offset) => `${String(offset).padStart(10, '0')} 00000 n \n`).join('');
  out += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`;
  return Buffer.from(out, 'latin1');
}

function pdfLines(index) {
  const header = [
    `Document placeholder ${index} / Document de exemplu ${index}`,
    '',
    'TODO(content): replace this file with the real research document.',
    'TODO(content): de înlocuit acest document cu documentul real.',
    '',
    'This file is generated by scripts/make-placeholder-assets.mjs. It contains no research',
    'and carries no claims. It only exists so that links and file-size labels can be built',
    'and tested before the real PDFs are supplied.',
    '',
  ];
  // Vary the length so the generated files have different sizes (roughly 2 to 12 KB).
  const fillerCount = 10 + index * 18;
  const filler = Array.from(
    { length: fillerCount },
    (_, i) => `Filler line ${i + 1} - placeholder text, no meaning / text de umplere, fara sens.`,
  );
  return [...header, ...filler];
}

const researchDir = join(root, 'public', 'research');
mkdirSync(researchDir, { recursive: true });
for (let i = 1; i <= PDF_COUNT; i += 1) {
  const name = `placeholder-${String(i).padStart(2, '0')}.pdf`;
  const bytes = buildPdf(pdfLines(i));
  writeFileSync(join(researchDir, name), bytes);
  console.log(`wrote public/research/${name} (${bytes.length} bytes)`);
}

/* ------------------------------------------------------------------ SVGs */

function svgPlaceholder({ fill, ink, title, label }) {
  return [
    '<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="800" viewBox="0 0 1200 800" role="img" aria-labelledby="title">',
    `  <title id="title">${title}</title>`,
    `  <rect width="1200" height="800" fill="${fill}"/>`,
    `  <text x="600" y="400" fill="${ink}" font-family="-apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif" font-size="44" font-weight="600" text-anchor="middle" dominant-baseline="middle">${label}</text>`,
    '</svg>',
    '',
  ].join('\n');
}

const blogPalette = ['#C9DDF2', '#CFE8D4', '#F2DCC9', '#E0D6F2'];
const blogDir = join(root, 'src', 'assets', 'blog');
mkdirSync(blogDir, { recursive: true });
blogPalette.forEach((fill, index) => {
  const n = index + 1;
  const name = `cover-${String(n).padStart(2, '0')}.svg`;
  writeFileSync(
    join(blogDir, name),
    svgPlaceholder({
      fill,
      ink: '#1D1D1F',
      title: `Placeholder article cover ${n}`,
      label: `Copertă exemplu ${n} / Placeholder cover ${n}`,
    }),
  );
  console.log(`wrote src/assets/blog/${name}`);
});
